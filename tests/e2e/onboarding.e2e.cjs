const { chromium, devices } = require('playwright')
const BASE = process.env.BASE || 'http://localhost:3100'
const OUT = process.env.OUT || require('os').tmpdir()
;(async () => {
  const b = await chromium.launch()
  const ctx = await b.newContext({ ...devices['iPhone 14'], locale: 'tr-TR', timezoneId: 'Europe/Istanbul' })
  const p = await ctx.newPage()
  p.setDefaultNavigationTimeout(60000)
  const errors = []
  p.on('pageerror', (e) => errors.push('pageerror: ' + e.message))
  p.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()) })
  const shot = (n) => p.screenshot({ path: `${OUT}/${n}.png`, fullPage: true })
  const u = 'test_' + Date.now().toString(36)
  const fail = (m) => { throw new Error(m) }

  await p.goto(BASE + '/kayit')
  await p.fill('#username', u)
  await p.fill('#email', u + '@gmial.com')
  await p.waitForTimeout(600)
  await p.getByText('Bunu mu demek istedin?').click()
  await p.fill('#password', 'Deneme1234')
  await p.fill('#confirm', 'Deneme1234')
  await p.check('input[name=terms]')
  await p.waitForTimeout(500)
  await shot('01-kayit')
  await p.getByRole('button', { name: 'Hesabı oluştur' }).click()
  await p.waitForURL('**/kurulum')
  await shot('02-kurulum-0')
  const next = () => p.getByRole('button', { name: /Devam|Başlayalım/ }).click()
  await next()
  await p.getByRole('button', { name: 'Erkek' }).click(); await next()
  await p.fill('#bd', '1998-03-14'); await shot('03-dogum'); await next()
  // boy: 177 — butonlarla
  for (let i = 0; i < 7; i++) await p.getByRole('button', { name: 'Artır' }).click()
  await p.waitForTimeout(400); await shot('04-boy'); await next()
  // kilo: klavye ile 78.4 (70 + 84 adım)
  const slider = p.getByRole('slider', { name: 'Kilo' })
  await slider.focus()
  for (let i = 0; i < 8; i++) await p.keyboard.press('Shift+ArrowRight')
  for (let i = 0; i < 4; i++) await p.keyboard.press('ArrowRight')
  await p.waitForTimeout(500); await shot('05-kilo'); await next()
  await p.getByRole('button', { name: /Orta hareketli/ }).click(); await next()
  await p.getByRole('button', { name: /Kilo vermek/ }).click(); await next()
  // hedef 72: otomatik 73.4→ 73.5? ayarla
  const tv = await p.getByRole('slider', { name: 'Hedef kilo' }).getAttribute('aria-valuenow')
  let cur = Number(tv)
  while (cur > 72) { await p.getByRole('button', { name: 'Azalt' }).click(); cur -= 0.5 }
  await p.waitForTimeout(500); await shot('06-hedef'); await next()
  await p.getByRole('button', { name: /Kendim belirleyeceğim/ }).click()
  await p.fill('input[aria-label="Gün sayısı"]', '30')
  await p.waitForTimeout(300); await shot('07-tempo-guvensiz')
  // 6,4 kg / 30 gün ≈ 1,49 kg/hf: güvenli değil ama kullanıcının seçimi → uyarı + devam edilebilir
  const nextBtn = p.getByRole('button', { name: /Devam/ })
  if (!(await p.getByText(/önerilen sınırın üstünde, güvenli değil/).count())) fail('güvensiz tempo uyarısı yok')
  if (await nextBtn.isDisabled()) fail('kullanıcının seçtiği tempo engellenmemeli')
  // 20 gün ≈ 2,2 kg/hf: mutlak sınır (1,5 kg/hf) aşılır → devam kapalı, en kısa süre düğmesi
  await p.fill('input[aria-label="Gün sayısı"]', '20')
  await p.waitForTimeout(200)
  if (!(await nextBtn.isDisabled())) fail('haftada 1,5 kg üstü engellenmeli')
  await p.getByRole('button', { name: /günü kullan/ }).click()
  if (await nextBtn.isDisabled()) fail('en kısa süre seçilince devam açılmalı')
  await p.getByRole('button', { name: /Dengeli/ }).click()
  await p.waitForTimeout(300); await shot('07b-tempo'); await next()
  await p.getByRole('button', { name: 'Orta' }).click()
  await p.getByRole('button', { name: '4', exact: true }).click()
  await shot('08-ek'); await next()
  await p.waitForTimeout(400); await shot('09-plan')
  await p.getByRole('button', { name: /Planı başlat/ }).click()
  await p.waitForURL(BASE + '/')
  await p.waitForTimeout(800); await shot('10-bugun')
  // hızlı ekle → kilo
  await p.getByRole('button', { name: 'Hızlı ekle' }).click()
  await p.waitForTimeout(300); await shot('11-hizli-ekle')
  await p.getByRole('button', { name: /Kilo gir/ }).click()
  await p.fill('#qa-kg', '78,1')
  await p.getByRole('button', { name: 'Kaydet' }).click()
  await p.waitForTimeout(1200); await shot('12-bugun-kilo')
  await p.goto(BASE + '/profil'); await shot('13-profil')
  await p.goto(BASE + '/su'); await shot('14-su')
  await p.goto(BASE + '/profil'); await p.getByRole('button', { name: /Çıkış yap/ }).click()
  await p.waitForURL('**/giris')
  await p.fill('#login', u); await p.fill('#password', 'yanlis'); await p.getByRole('button', { name: 'Giriş yap' }).click()
  await p.waitForTimeout(600); await shot('15-giris-hata')
  await p.fill('#password', 'Deneme1234'); await p.getByRole('button', { name: 'Giriş yap' }).click()
  await p.waitForURL(BASE + '/')
  console.log('E2E OK user=', u)
  console.log(errors.length ? errors.join('\n') : 'no console errors')
  await b.close()
})().catch((e) => { console.error('E2E FAIL', e.message); process.exit(1) })
